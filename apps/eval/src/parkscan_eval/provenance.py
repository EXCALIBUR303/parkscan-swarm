"""Where a result came from: git SHA, config hash, library versions.

A number without provenance is not a result, it is an anecdote. ``docs/ACCEPTANCE.md`` A11
requires that every claimed metric be regenerated by a committed harness from a committed
input, and that is only checkable if each output file says which commit, which
configuration and which library versions produced it.

Nothing here is a metric, so nothing here is pure: this module runs ``git`` and reads
installed package metadata. It is kept separate from :mod:`parkscan_eval.metrics` for
exactly that reason.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

__all__ = [
    "TRACKED_LIBRARIES",
    "Provenance",
    "config_hash",
    "describe",
    "git_revision",
    "library_versions",
]

TRACKED_LIBRARIES: tuple[str, ...] = (
    "numpy",
    "parkscan-core",
    "parkscan-eval",
    "parkscan-perception",
    "parkscan-sim",
)
"""Distributions whose version can change a number in ``results.csv``. Sorted, so the
recorded mapping has a stable order regardless of how it was assembled."""

_UNKNOWN = "unknown"
_NOT_INSTALLED = "not-installed"


@dataclass(frozen=True, slots=True)
class Provenance:
    """Everything needed to say which code and which inputs produced a result file."""

    git_sha: str
    git_dirty: bool
    config_hash: str
    python: str
    libraries: tuple[tuple[str, str], ...]

    def as_dict(self) -> dict[str, object]:
        """JSON-ready form, with the library versions as a plain sorted mapping."""
        return {
            "git_sha": self.git_sha,
            "git_dirty": self.git_dirty,
            "config_hash": self.config_hash,
            "python": self.python,
            "libraries": dict(self.libraries),
        }


def git_revision(repo_root: Path) -> tuple[str, bool]:
    """``(sha, dirty)`` for ``repo_root``, or ``("unknown", False)`` if git cannot answer.

    ``dirty`` is true when the working tree has uncommitted changes, which is the state a
    result file must not hide: a metric produced from an edited tree cannot be regenerated
    from the recorded SHA, and saying so is the whole point of recording it.
    """
    try:
        # Fixed argv, no shell, no interpolated input. `check=True` turns a non-zero
        # exit into the same "git cannot answer" path as git being absent entirely.
        sha = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=True,
            timeout=10,
        ).stdout.strip()
        status = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=True,
            timeout=10,
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return (_UNKNOWN, False)
    return (sha or _UNKNOWN, bool(status.strip()))


def library_versions(names: Sequence[str] = TRACKED_LIBRARIES) -> tuple[tuple[str, str], ...]:
    """Installed version of each distribution, ``"not-installed"`` when absent.

    A missing entry is reported rather than omitted. ``parkscan-eval`` itself is commonly
    run from source with ``PYTHONPATH`` and no wheel installed, and a silently absent row
    would read as "this library was not involved".
    """
    resolved: list[tuple[str, str]] = []
    for name in sorted(names):
        try:
            resolved.append((name, version(name)))
        except PackageNotFoundError:
            resolved.append((name, _NOT_INSTALLED))
    return tuple(resolved)


def config_hash(config: Mapping[str, object]) -> str:
    """SHA-256 over the canonical JSON form of ``config``.

    ``sort_keys`` and fixed separators make the digest independent of how the mapping was
    built, so two runs that used the same parameters hash the same even if the code that
    assembled the dictionary changed shape.
    """
    canonical = json.dumps(config, sort_keys=True, separators=(",", ":"), default=str)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def describe(repo_root: Path, config: Mapping[str, object]) -> Provenance:
    """Collect the whole provenance record in one call."""
    sha, dirty = git_revision(repo_root)
    return Provenance(
        git_sha=sha,
        git_dirty=dirty,
        config_hash=config_hash(config),
        python=sys.version.split()[0],
        libraries=library_versions(),
    )
